def classify(question,theme_rules):
    theme=clean(question['theme'])
    if question['pack_id']==24974:
        result={'anime':(.95,'anime_pack_context')}
        if re.search(r'музыка|сопутствующий трек|перемотка|не досмотрят',theme):result['music']=(.8,'theme_context')
        return result
    if question['pack_id']==15714:return {'geography':(.95,'geography_pack_context')}
    if theme=='рататуй':return {'animation':(.95,'theme_context'),'food':(.9,'theme_context')}
    primary=OVERRIDES.get(theme)
    if primary is None:
        matches=[slug for slug,pattern in theme_rules.items() if re.search(pattern,theme,re.I)]
        if matches:return {slug:(.9,'theme_keyword') for slug in matches}
        primary='everyday'
    if primary!='everyday':return {primary:(.9,'theme_context')}
    matches=[slug for slug,pattern in BODY.items() if re.search(pattern,question['prompt'],re.I)]
    if matches:return {slug:(.65,'question_text_keyword_unreviewed') for slug in matches[:3]}
    return {'everyday':(0.0,'unclassified_requires_review')}
