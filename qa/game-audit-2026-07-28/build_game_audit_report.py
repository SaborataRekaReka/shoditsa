def add_two_pictures(doc, left_path, right_path, caption):
    table = doc.add_table(rows=1, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    for cell, path in zip(table.rows[0].cells, (left_path, right_path)):
        set_cell_border(cell, color="FFFFFF")
        set_cell_margins(cell, top=0, start=40, bottom=0, end=40)
        p = cell.paragraphs[0]
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        if path.exists():
            p.add_run().add_picture(str(path), width=Inches(2.65))
    add_caption(doc, caption)


